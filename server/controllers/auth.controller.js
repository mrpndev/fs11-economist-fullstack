// import your user model
const { User } = require("../models/auth.model");
// import bcrypt
const bcrypt = require("bcrypt");
// ? salt - random value added to our hash
const SALT = Number(process.env.SALT);
// import jsonwebtoken
const jwt = require("jsonwebtoken");
// import our secret key
const JWT_KEY = process.env.JWT_KEY;


let registerUser = async (req, res) => {
	let { full_name, email, address, password } = req.body;

	// call create on your User schema and pass the data
	let newUser = await User.create({
		full_name: full_name,
		email: email,
		address: address,
		// ? generate hash of the password
		password: bcrypt.hashSync(password, SALT),
	});

	// ? Generate a token
	const token = jwt.sign(
		// payload (user id information)
		{ id: newUser.dataValues.id },
		JWT_KEY,
		// options (expiration)
		{ expiresIn: "24h" }
	);

	res.status(201).json({
		message: `User created`,
		newUser,
		token,
	});
};

let loginUser = async (req, res) => {
	const { email, password } = req.body;

	// findOne accepts query object where we match email from db to email from req
	// let foundUser = await User.findOne({ where: { email: req.body.email }})

	let foundUser = await User.findOne({ where: { email } });

	if (!foundUser) {
		res.status(403).json({
			message: "Invalid username or password",
		});

		return;
	}

	/* 
		? Implement JWT in login route
	*/

	// example of object destructuring and giving it an alias
	let { dataValues: user } = foundUser;

	// ? compare database password (hash) with that of the user (pwd)
	let verifyPwd = await bcrypt.compare(password, user.password);

	if (!verifyPwd) {
		res.status(403).json({
			message: "Invalid username or password",
		});

		return;
	}

	const token = jwt.sign(
		// payload (user id information)
		{ id: user.id },
		JWT_KEY,
		// options (expiration)
		{ expiresIn: "24h" }
	);

	res.status(200).json({
		message: `${user.email} logged in`,
		token
	});
};

let resetPassword = async (req, res) => {
	const { email, currentPassword, newPassword } = req.body;

	// let foundUser = await User.findOne({ where: { email } });

	// if (!foundUser) {
	// 	return res.status(500).json({
	// 		message: "User not found",
	// 	});
	// }

	let validPassword = await bcrypt.compare(currentPassword, req.user.password)

	if (!validPassword) {
		return res.status(403).json({
			message: "Incorrect current password"
		})
	}

	req.user.password = bcrypt.hashSync(newPassword, SALT);

	await req.user.save();

	res.status(200).json({
		message: "Password Updated",
	});
};

module.exports = { registerUser, loginUser, resetPassword };

/* 
	? Authentication vs Authorization
	* authentication
		* process of proving who you are
		* for ex: checking your username and password
	* authorization
		* process of proving you have permissons to access a resource
*/

/* 
	? Password Hashing
	* process of encrypting our password
	* a one way process
	* once hashed, it cannot be unhashed
	* common attack: rainbow table attack
	
	? How Does it Work
	* we hash the password to obfuscate the data
	* we then verify if the hash has been created by us
	* we will use library called bcrypt
*/

/* 
	? Authorization
	* process of establishing a session
	* sessionID generated server-side passed to the client
	* client makes subsequent requests with this sessionID
	* sessionID is the key to protected routes
	! problem - session can only be generated per server (without any other services)
*/

/* 
	? JSON Web Token (JWT)
	* a token that is generated by the server
	* it is server-agnostic
	* verified against a secret
	* wherever the secret exists, the token can be verified
	* consists of
		* header
			* contains the encryption algorithm
			* type of token
		* payload
			* data
			! data is not encrypted and is visible to anyone who can intercept it
		* secret
			* key used to authorize/verify the token
*/
